export function knowledgeForUnit(bookKey, no) {
  const entry = UNITS[bookKey]?.[Number(no) - 1];
  if (!entry) throw new Error(`缺少人教版单元知识数据：${bookKey} 第 ${no} 单元`);
  return entry;
}

export function knowledgeCoverage() {
  return Object.fromEntries(Object.entries(UNITS).map(([key, units]) => [key, units.length]));
}
