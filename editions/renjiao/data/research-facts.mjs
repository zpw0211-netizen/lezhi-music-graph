const normalizeBookKey = (bookKey) => String(bookKey).replace(/^pep-/u, "");

export function researchFactsFor(bookKey) {
  if (!String(bookKey).startsWith("pep-")) return [];
  return packs
    .filter((pack) => normalizeBookKey(pack.bookKey) === normalizeBookKey(bookKey))
    .flatMap((pack) => pack.facts.map(([predicate, value, valueType]) => ({
      anchorName: pack.anchorName,
      anchorType: pack.anchorType,
      predicate,
      value,
      valueType,
      page: pack.page,
      source: sources[pack.source],
    })));
}

export const researchCoverage = Object.fromEntries(
  [...new Set(packs.map((pack) => normalizeBookKey(pack.bookKey)))].map((bookKey) => [
    bookKey,
    packs.filter((pack) => normalizeBookKey(pack.bookKey) === bookKey).reduce((count, pack) => count + pack.facts.length, 0),
  ]),
);
