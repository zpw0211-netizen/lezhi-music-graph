import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const edition = path.join(process.cwd(), "editions", "renjiao-staff");
const index = JSON.parse(await readFile(path.join(edition, "data", "wx-pep-work-index.json"), "utf8"));
const audit = JSON.parse(await readFile(path.join(edition, "data", "wx-pep-scan-audit.json"), "utf8"));
const booksPath = path.join(edition, "data", "books.json");
const registry = JSON.parse(await readFile(booksPath, "utf8"));
const sourceRegistry = JSON.parse(await readFile(path.join(process.cwd(), "editions", "renjiao", "data", "books.json"), "utf8"));
const auditBooks = new Map(audit.books.map((book) => [book.key, book]));
const registryBooks = new Map(registry.books.map((book) => [book.key, book]));
const sourceBooks = new Map(sourceRegistry.books.map((book) => [book.key, book]));
const summaries = [];
const rows = [];

for (const book of index.books) {
  const scan = auditBooks.get(book.key);
  if (!scan) throw new Error(`Missing scan audit for ${book.key}`);
  const scanWorks = new Map(scan.works.map((work) => [work.title, work]));
  const works = book.works.map((work) => {
    const checked = scanWorks.get(work.title);
    if (!checked) throw new Error(`Missing work audit: ${book.key} / ${work.title}`);
    const mapped = {
      title: work.title,
      units: work.units,
      jianpuPages: work.pages,
      jianpuScoreCrops: work.scoreCrops,
      staffPages: checked.staffPages,
      staffScoreCrops: checked.verifiedScoreCrops,
      pageStatus: checked.pageStatus,
      cropStatus: checked.cropStatus,
      matchEvidencePages: checked.matchedPages,
      manualNote: checked.manualNote,
      visualEvidence: checked.visualEvidence ?? null,
    };
    rows.push({ book, work: mapped });
    return mapped;
  });

  const manifest = {
    bookKey: book.key,
    title: book.title,
    sourcePdf: scan.sourcePdf,
    pdfPageCount: scan.pdfPageCount,
    printedPageCount: scan.printedPageCount,
    pdfOffset: scan.pdfOffset,
    coverChecks: scan.coverChecks,
    works,
  };
  const shortKey = book.key.replace(/^pep-/, "");
  const out = path.join(edition, "scripts", `wx-pep-${shortKey}.mjs`);
  await writeFile(out, `// PDF text matches plus explicit visual corrections; generated by build-wx-pep-maps.mjs.\nexport default ${JSON.stringify(manifest, null, 2)};\n`, "utf8");

  const statusCounts = Object.fromEntries(["matched", "moved", "manual", "ambiguous", "missing"].map((status) => [status, works.filter((work) => work.pageStatus === status).length]));
  summaries.push({ ...book, jianpuPages: sourceBooks.get(book.key)?.pages, printedPages: scan.printedPageCount, pdfOffset: scan.pdfOffset, sourcePdf: scan.sourcePdf, pdfPageCount: scan.pdfPageCount, coverChecks: scan.coverChecks, statusCounts, verifiedCrops: works.filter((work) => work.cropStatus === "verified").length });
  const targetBook = registryBooks.get(book.key);
  if (!targetBook) throw new Error(`No target books.json entry for ${book.key}`);
  if (!scan.coverChecks.fiveLineNotation || !scan.coverChecks.pepPublisher) throw new Error(`Scan identity check failed: ${book.key}`);
  targetBook.pages = scan.printedPageCount;
  targetBook.pdfOffset = scan.pdfOffset;
}
await writeFile(booksPath, `${JSON.stringify(registry, null, 2)}\n`, "utf8");

