// 自动提取或旧数据里的这些角色一律丢掉，只用上表。
const CREATOR_ROLES = new Set(["作词", "作曲", "词曲作者", "填词", "译配", "译词", "编曲", "编配", "改编", "改词", "编词", "配歌", "配曲", "配合唱", "编合唱", "整理", "整理者", "整理改编", "记谱", "记谱配词", "记录", "记录者", "传谱", "编剧", "执笔"]);
const bare = (title) => String(title).replace(/^《|》$/g, "").replace(/\s+/g, "");

/** Replaces every work's creator facts with the page-checked credits above (printed page = the work's own page). */
export function withCredits(bookKey, parts) {
  const book = CREDITS[bookKey] ?? {};
  const byTitle = new Map(Object.entries(book).map(([title, items]) => [bare(title), items]));
  return parts.map((part) => ({
    ...part,
    works: part.works.map((work) => {
      const credits = byTitle.get(bare(work.name)) ?? [];
      const facts = (work.facts ?? []).filter(([predicate]) => !CREATOR_ROLES.has(predicate));
      return { ...work, facts: [...facts, ...credits.map(([role, name]) => [role, name, "人物", "明", work.page])] };
    }),
  }));
}
