type TupletGroup = [voice: number, bar: number, start: number, count: number, beats: number];

// Use the durations of the printed groups that jianpu's tuplet shorthand cannot express.
function withTuplets(melody: Melody, groups: TupletGroup[]): Melody {
  const lines = [melody.bars, ...(melody.voices ?? []).map(({ bars }) => bars)];
  for (const [voice, bar, start, count, beats] of groups) {
    for (const note of lines[voice][bar].slice(start, start + count)) {
      note.b = beats / count;
      note.tuplet = count;
    }
  }
  return melody;
}

